    public void readJTable() {
        DefaultTableModel modelo = (DefaultTableModel) pedidos_table.getModel();
        modelo.setNumRows(0);

        for (Cliente c : new Cliente_DAO().read()) {

            modelo.addRow(new Object[]{
                c.getId(),
                c.getNome(),
                c.getTelefone(),
                c.getCanalContato()
            });
        }
    }

