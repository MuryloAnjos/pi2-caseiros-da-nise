        public void readJTable() {
        DefaultTableModel modelo = (DefaultTableModel) pedidos_table.getModel();
        modelo.setNumRows(0);

        LocalDate hoje = LocalDate.now();
        LocalDate limite = hoje.plusDays(7);
        DateTimeFormatter f = DateTimeFormatter.ofPattern("dd/MM/yyyy");

        Cliente_DAO cdao = new Cliente_DAO();

        for (Pedido p : new Pedido_DAO().read()) {

            boolean dentroDaSemana = !p.getDataEntrega().isBefore(hoje)
                    && !p.getDataEntrega().isAfter(limite);
            boolean aberto = !p.getSituacao().equals("ENTREGUE")
                    && !p.getSituacao().equals("CANCELADO");

            if (dentroDaSemana && aberto) {
                modelo.addRow(new Object[]{
                    p.getId(),
                    cdao.consul(p.getClienteId()).getNome(),
                    p.getDataEntrega().format(f),
                    p.getSituacao()
                });
            }
        }
    }

