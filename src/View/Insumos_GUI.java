    public void readJTable() {
        DefaultTableModel modelo = (DefaultTableModel) pedidos_table.getModel();
        modelo.setNumRows(0);

        for (Insumo i : new Insumo_DAO().read()) {
            modelo.addRow(new Object[]{
                i.getId(),
                i.getNome(),
                i.getUnidade(),
                String.format("%.6f", i.getPreco()),
                String.format("%.0f", i.getQtdEstoque()),
                String.format("%.0f", i.getQtdMinima())
            });
        }
    }
    
    public void readJTableMinimo() {
        DefaultTableModel modelo = (DefaultTableModel) pedidos_table.getModel();
        modelo.setNumRows(0);

        for (Insumo i : new Insumo_DAO().readAbaixoDoMinimo()) {
            modelo.addRow(new Object[]{
                i.getId(),
                i.getNome(),
                i.getUnidade(),
                String.format("%.6f", i.getPreco()),
                String.format("%.0f", i.getQtdEstoque()),
                String.format("%.0f", i.getQtdMinima())
            });
        }
    }


