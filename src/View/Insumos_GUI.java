    private void calcular_BTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_calcular_BTNActionPerformed
        // TODO add your handling code here:
        if (qtdcompra_txt.getText().trim().isEmpty() || pago_txt.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Preencha a quantidade comprada e o valor pago.");
            return;
        }
        String emb = embalagem_cmb.getSelectedItem().toString();
        double fator = 1;
        if (emb.equals("kg") || emb.equals("l")) {
            fator = 1000;
        } else if (emb.equals("dúzia")) {
            fator = 12;
        }

        double preco = new Insumo_DAO().calcularPrecoUnitario(
                numero(qtdcompra_txt.getText()), fator, numero(pago_txt.getText()));
        preco_txt.setText(String.format("%.6f", preco));

        if (emb.equals("kg")) unidade_cmb.setSelectedItem("g");
        if (emb.equals("l")) unidade_cmb.setSelectedItem("ml");
        if (emb.equals("dúzia")) unidade_cmb.setSelectedItem("un");
    
    }//GEN-LAST:event_calcular_BTNActionPerformed

    private void minimo_BTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_minimo_BTNActionPerformed
        // TODO add your handling code here:
        if (minimo_BTN.getText().equals("Ver abaixo do mínimo")) {
            readJTableMinimo();
            if (pedidos_table.getRowCount() == 0) {
                JOptionPane.showMessageDialog(this, "Nenhum insumo abaixo do mínimo.");
                readJTable();
                return;
            }
            minimo_BTN.setText("Ver todos");
        } else {
            readJTable();
            minimo_BTN.setText("Ver abaixo do mínimo");
        }
    }//GEN-LAST:event_minimo_BTNActionPerformed

