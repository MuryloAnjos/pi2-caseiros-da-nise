    private void buscar_BTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buscar_BTNActionPerformed
        // TODO add your handling code here:
        if (id_txt.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Digite o Id do produto.");
            return;
        }
        Produto p = new Produto_DAO().consul(Integer.parseInt(id_txt.getText().trim()));
        if (p == null) {
            JOptionPane.showMessageDialog(this, "Produto não encontrado.");
            return;
        }
        nome_txt.setText(p.getNome());
        categoria_cmb.setSelectedItem(p.getCategoria());
        tempo_txt.setText(String.valueOf(p.getTempoPreparoMin()));
        margem_txt.setText(String.format("%.0f", p.getMargem()));
        preco_txt.setText(String.format("%.2f", p.getPrecoVenda()));
    }//GEN-LAST:event_buscar_BTNActionPerformed

    private void editar_BTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_editar_BTNActionPerformed
        // TODO add your handling code here:
        if (id_txt.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Selecione um produto na tabela ou busque pelo Id.");
            return;
        }
        Produto p = new Produto(
                nome_txt.getText().trim(),
                categoria_cmb.getSelectedItem().toString(),
                Integer.parseInt(tempo_txt.getText().trim()),
                numero(margem_txt.getText()),
                numero(preco_txt.getText()));
        p.setId(Integer.parseInt(id_txt.getText().trim()));
        new Produto_DAO().update(p);
        readJTable();
        limpar();
    }//GEN-LAST:event_editar_BTNActionPerformed

    private void excluir_BTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_excluir_BTNActionPerformed
        // TODO add your handling code here:
        if (id_txt.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Selecione um produto na tabela ou busque pelo Id.");
            return;
        }
        int op = JOptionPane.showConfirmDialog(this,
                "Excluir o produto " + nome_txt.getText() + "?", "Excluir",
                JOptionPane.YES_NO_OPTION);
        if (op == JOptionPane.YES_OPTION) {
            Produto p = new Produto();
            p.setId(Integer.parseInt(id_txt.getText().trim()));
            new Produto_DAO().delete(p);
            readJTable();
            limpar();
        }
    }//GEN-LAST:event_excluir_BTNActionPerformed

